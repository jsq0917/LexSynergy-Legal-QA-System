_NOISE_RE = re.compile("|".join(sorted((re.escape(w) for w in QUESTION_NOISE), key=len, reverse=True)))


def strip_question_noise(query: str) -> str:
    """剥掉疑问词与语气词，保留实体与术语。"""
    text = _NOISE_RE.sub(" ", query or "")
    text = re.sub(r"[，。！？；、,.!?;:：\s]+", " ", text).strip()
    return text or (query or "").strip()


def expand_terms(query: str) -> str:
    """命中口语词则拼接对应法条用语；多命中按出现顺序去重拼接。"""
    q = query or ""
    parts: list[str] = []
    for keywords, expansion in TERM_EXPANSIONS:
        if any(kw in q for kw in keywords) and expansion not in parts:
            parts.append(expansion)
    return " ".join(parts)


def query_variants(query: str) -> list[str]:
    """返回去重后的查询变体：原句 / 去噪 / 去噪+术语扩展。"""
    original = (query or "").strip()
    core = strip_question_noise(original)
    expansion = expand_terms(original)
    variants = [original]
    if core and core != original:
        variants.append(core)
    if expansion:
        variants.append(f"{core} {expansion}".strip())
    seen: set[str] = set()
    out: list[str] = []
    for v in variants:
        if v and v not in seen:
            seen.add(v)
            out.append(v)
    return out
